// Generates packages/connector-installer-core/pdpp-source-contract.mjs from
// the PDPP reference contract's own SourceDeclaration module, so the builder
// and the installer run the normative schema and semantic validator instead
// of a hand port. `@pdpp/reference-contract` is private and TypeScript-only,
// so the pinned upstream file is vendored verbatim and type-stripped here;
// stripping only blanks type syntax, it does not rewrite any logic.
//
//   node scripts/generate-pdpp-source-contract.mjs             regenerate
//   node scripts/generate-pdpp-source-contract.mjs --check     offline drift check
//   node scripts/generate-pdpp-source-contract.mjs --upstream  also compare the
//       vendored file with the pinned upstream commit and report whether PDPP
//       main has moved since (network)

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";

const UPSTREAM = {
	repository: "PDP-Connect/pdpp",
	commit: "ab415be6cc1df9ad544505084f952b7a8726f29e",
	path: "packages/reference-contract/src/public/source.ts",
	sha256: "a8d5699e088d8da501da0294d0668934cfebbd5d3d4d1320624d028a7063380d",
};

const vendored = new URL("../vendor/pdpp-reference-contract/source.ts", import.meta.url);
const destination = new URL(
	"../packages/connector-installer-core/pdpp-source-contract.mjs",
	import.meta.url,
);

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const rawUrl = (ref) =>
	`https://raw.githubusercontent.com/${UPSTREAM.repository}/${ref}/${UPSTREAM.path}`;

const source = readFileSync(vendored, "utf8");
if (sha256(source) !== UPSTREAM.sha256) {
	throw new Error(
		`vendor/pdpp-reference-contract/source.ts is not ${UPSTREAM.repository}@${UPSTREAM.commit}:${UPSTREAM.path}; copy that file verbatim or update the pin`,
	);
}

const generated = [
	"// Generated by scripts/generate-pdpp-source-contract.mjs. Do not edit.",
	`// Type-stripped from ${UPSTREAM.repository}@${UPSTREAM.commit}`,
	`// ${UPSTREAM.path} (sha256 ${UPSTREAM.sha256}).`,
	stripTypeScriptTypes(source, { mode: "strip" }),
].join("\n");

if (process.argv.includes("--upstream")) {
	const pinned = await (await fetch(rawUrl(UPSTREAM.commit))).text();
	if (pinned !== source) {
		throw new Error(`vendored source.ts differs from ${rawUrl(UPSTREAM.commit)}`);
	}
	const main = await (await fetch(rawUrl("main"))).text();
	console.log(
		main === source
			? `pinned source.ts matches ${UPSTREAM.repository} main`
			: `${UPSTREAM.repository} main has changed ${UPSTREAM.path} since the pin; review and re-pin`,
	);
}

if (process.argv.includes("--check") || process.argv.includes("--upstream")) {
	if (readFileSync(destination, "utf8") !== generated) {
		throw new Error("pdpp-source-contract.mjs is stale; run npm run pdpp-source-contract:generate");
	}
} else {
	writeFileSync(destination, generated);
}
